// دو هشدار که اپ از قبل می‌دانستشان و فقط در لاگ می‌نوشت. لاگ را کسی وسط دیکته
// نمی‌خواند، پس هر دو تا امروز عملا وجود نداشتند (باگ‌های B8 و B9).
//
// چرا یک فایلِ جدا و نه دو خط در session.m: هر دو یک تصمیم‌اند («این را همین حالا
// به کاربر بگو یا نه») و هر دو آستانه دارند، و آستانه‌ی بی‌تست همان حدسی است که
// فردا کسی عوضش می‌کند. اینجا هر دو تابع خالص‌اند و tools/deafmic_test.sh رویشان
// می‌دود.
#import "zemzeme.h"
#import "warn.h"

// ---------- B8: میان‌بر با دیکته‌ی خودِ مک یکی است ----------
// شرحِ کاملِ برخورد و اینکه چرا خودمان درستش نمی‌کنیم، سرِ `ZMacDictationOnDoubleCommand`
// در app.m است. اینجا فقط تصمیمِ «کِی بگو» است.
//
// یک بار در هر اجرای اپ، نه هر سشن: تنظیمِ سیستم وسطِ کار عوض نمی‌شود و هشداری که
// سرِ هر دیکته تکرار شود، سومین بار دیگر خوانده نمی‌شود. و خاموش‌کردنی هم هست:
// کاربر که میان‌بر مک را عوض کند، `ZMacDictationOnDoubleCommand` نه می‌گوید و این
// هشدار دیگر هیچ‌وقت نمی‌آید.
NSString *ZClashWarning(void) {
    static BOOL told = NO;      // نخ اصلی، سرِ شروعِ سشن
    if (told || !ZMacDictationOnDoubleCommand()) return nil;
    told = YES;
    ZLog(@"warn: برخوردِ میان‌بر به پنل رفت، نه فقط به لاگ");
    return @"دیکته‌ی خودِ مک هم روی دو بار Command است؛ در تنظیمات سیستم › Keyboard › Dictation خاموشش کن";
}

// ---------- B9: میکروفن بایت می‌دهد ولی هیچ حرفی در آن نیست ----------
// نگهبانِ `armDeafWatchdog` در audio.m فقط **صفر بایت** را می‌گیرد. سشنِ ۲۰۲۶-۰۸-۱۸
// ساعت ۰۵:۴۱:۰۸ از آن در رد شد: پنج دقیقه صدا رسید (rms ۰٫۰۰۵ تا ۰٫۰۱۶، snr ۱۷ تا
// ۲۷ دسی‌بل)، ۴۷ تکه به سرور رفت، هر ۴۷ تا «حرفی نبود» برگشت، و کاربر صفر نویسه و
// صفر خطا دید تا سقفِ پنج دقیقه رسید.
//
// **سنجه‌ی درست، همان حکمی است که صف از قبل دارد، نه یک آستانه‌ی تازه روی rms.**
// سندِ باگ «rms زیر kZVoiceRMS برای N ثانیه» را پیشنهاد کرده بود و داده ردش می‌کند:
// در همین app.log ۲۹۰۲ خطِ `mic: rms` هست و ۱٫۵٪ شان زیر kZVoiceRMS اند، با یک
// رشته‌ی ۹ تایی (۹۰ ثانیه) در سشنی که سالم بود و متن هم داد. آن آستانه سرِ کاربری
// که آرام و از فاصله حرف می‌زند آژیر می‌کشید.
//
// و مهم‌تر: کاربری که ده ثانیه فکر می‌کند اصلا از این در رد نمی‌شود. خط لوله تکه‌ی
// بی‌حرف را همان‌جا می‌اندازد («سکوت، رد شد») و جایی در صف نمی‌گیرد، پس سکوتِ آدم
// هیچ‌وقت `ZSlotSilent` نمی‌سازد. `ZSlotSilent` یعنی صدا از دروازه‌ی `ZSegHasVoice`
// رد شده، یک رفت‌وبرگشتِ کامل خرج شده، و سرور خط را تمیز بسته و حرفی نشنیده.
//
// چرا پنج: شمارشِ کلِ ۷۳۸ سشنِ app.log (۲۴ ژوئیه تا ۲۸ اوت ۲۰۲۶) با شمردنِ
// «چند تکه‌ی پشتِ سرِ هم حرفی نبود، پیش از اولین متن»:
//   • ۶۷۶ سشنِ سالم (متن دادند): ۶۶۶ تا صفر، ۹ تا یکی، و بیشترین ۳ تا (یک بار).
//   • ۶۲ سشنِ بی‌متن: ۴۴ تا یکی، دو تا دو، یکی چهار، و یکی ۴۷ (همان سشنِ بالا).
// پس پنج، ۱٫۶۷ برابرِ بدترین چیزی است که یک سشنِ سالم تا امروز ساخته، و در کلِ آن
// تاریخ **یک بار** روشن می‌شود: روی همان سشنی که واقعا کر بود. آنجا تکه‌ی پنجم سرِ
// ۰۵:۴۱:۵۸ تمام شد، یعنی کاربر به‌جای پنج دقیقه، پنجاه ثانیه‌ای خبردار می‌شد.
static const NSInteger kZDeafSlots = 5;

// و چرا هشدار است نه `ZEngineGaveUp`ِ قرمز: قرمز `m.error` را روشن می‌کند و دکمه‌ی
// مکثِ پنل را به «دوباره تلاش کن (یک بار Command راست را بزن)» عوض می‌کند. روی
// میکروفنِ کر چیزی برای تلاشِ دوباره نیست و همان یک زدن، دورِ در جریان را می‌بندد.
// یعنی مثبتِ کاذب از خودِ باگ گران‌تر می‌شد. صدا همچنان ضبط می‌شود و متن هم اگر
// بیاید می‌نشیند، پس خبر لازم است نه وضعیتِ اضطراری.
NSString *ZDeafWarning(NSArray<ZSlot *> *slots) {
    NSInteger silent = 0;
    for (ZSlot *s in slots) {
        // پاس دومِ انگلیسی شمرده نمی‌شود: متنش تحویل کاربر نمی‌شود و **هر** جور
        // شکستش `ZSlotSilent` می‌شود، پس شمردنش آژیر را زودتر و بی‌دلیل می‌زد.
        if (s.extra) continue;
        if (s.state == ZSlotDone) return nil;   // یک متن آمد، پس میکروفن ثابت شد
        if (s.state == ZSlotSilent) silent++;
    }
    if (silent < kZDeafSlots) return nil;
    // دقیقا سرِ رسیدن به آستانه، یک بار در هر سشن: هر تغییرِ صف یک تکه است، پس این
    // شمار از پنج فقط یک بار رد می‌شود.
    if (silent == kZDeafSlots)
        ZLog(@"warn: %ld تکه‌ی پشتِ سرِ هم حرفی نداشت و هنوز هیچ متنی نیامده", (long)silent);
    return @"صدا می‌رسد ولی کلمه‌ای شنیده نمی‌شود؛ نزدیک‌تر حرف بزن یا در تنظیمات سیستم › Sound میکروفن را عوض کن";
}
