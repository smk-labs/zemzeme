#!/bin/bash
# تستِ طلایی: دفترِ اندازه. فایل‌های بزرگ اسم‌شان اینجاست و فقط اجازه‌ی کوچک‌شدن دارند.
#
# چرا این فایل هست: بدونِ دفتر، «تکه‌تکه کردن» خطِ پایان ندارد. هر کسی می‌تواند
# ۵۰۰ خط را از یک فایلِ بزرگ به یک فایلِ بزرگِ دیگر ببرد و اسمش را تمیزکاری بگذارد.
# دفتر آن را می‌گیرد: یک تکه‌تکه‌کردن تا وقتی نامِ فایل از دفتر بیرون نرود تمام نشده.
#
# اندازه‌گیری ۲۲ آگوست ۲۰۲۶، با همین دستور:
#   wc -l app/Sources-objc/*.m app/Sources-objc/*.h | awk '$1>700 && $2!="total"'
set -uo pipefail
cd "$(dirname "$0")/.."

CAP=700          # سقف: بالاتر از این باید عمدا در دفتر بنشیند
BUDGET=7738      # جمعِ خطوطِ بالای سقف در ۲۲ آگوست ۲۰۲۶. فقط پایین می‌آید.

# نامِ فایل و سنجاقش. هیچ‌کدام اجازه‌ی بالا رفتن ندارند.
# هر کدام هدفِ یک واحدِ تکه‌تکه‌کردن است؛ رفتنِ نام از این لیست یعنی آن واحد تمام شد.
PINS="
app/Sources-objc/app.m       1362
app/Sources-objc/batchui.m   1280
app/Sources-objc/panel.m     1135
app/Sources-objc/caret.m     1114
app/Sources-objc/zemzeme.h   1045
app/Sources-objc/final.m      969
app/Sources-objc/session.m    833
"

fail=0
pin_of() { echo "$PINS" | awk -v f="$1" '$1==f {print $2}'; }

# ---------- قاعده‌ی الف: فایلِ سنجاق‌شده بزرگ‌تر نمی‌شود ----------
while read -r f pin; do
  [ -n "${f:-}" ] || continue
  if [ ! -f "$f" ]; then
    printf '✗ دفتر: «%s» در دفتر است ولی فایل نیست. اگر جابه‌جا شد، دفتر را هم عوض کن.\n' "$f" >&2
    fail=1; continue
  fi
  n=$(wc -l < "$f" | tr -d ' ')
  if [ "$n" -gt "$pin" ]; then
    printf '✗ دفتر: %s از %s به %s رسید. فایل‌های دفتر فقط کوچک می‌شوند.\n' "$f" "$pin" "$n" >&2
    fail=1
  fi
done < <(echo "$PINS" | sed '/^[[:space:]]*$/d')

# ---------- قاعده‌ی ب: فایلِ بیرونِ دفتر از سقف رد نمی‌شود ----------
total=0
for f in app/Sources-objc/*.m app/Sources-objc/*.h; do
  n=$(wc -l < "$f" | tr -d ' ')
  [ "$n" -gt "$CAP" ] || continue
  total=$((total + n))
  if [ -z "$(pin_of "$f")" ]; then
    printf '✗ دفتر: %s با %s خط از سقف %s رد شد و در دفتر نیست.\n' "$f" "$n" "$CAP" >&2
    printf '   یا تکه‌اش کن، یا عمدا با دلیل به PINS اضافه‌اش کن (و بودجه باید جا بدهد).\n' >&2
    fail=1
  fi
done

# ---------- قاعده‌ی ج: بندِ جابه‌جایی ----------
# جمعِ خطوطِ بالای سقف فقط پایین می‌آید. این همان چیزی است که «هل دادنِ خط از یک
# فایلِ بزرگ به یک فایلِ بزرگِ دیگر» را از تمیزکاریِ واقعی جدا می‌کند.
if [ "$total" -gt "$BUDGET" ]; then
  printf '✗ دفتر: جمعِ خطوطِ بالای سقف %s شد، بودجه %s است.\n' "$total" "$BUDGET" >&2
  printf '   خط از یک فایلِ بزرگ به فایلِ بزرگِ دیگر رفته، نه بیرون. این جابه‌جایی است نه تمیزکاری.\n' >&2
  fail=1
fi

[ "$fail" = 0 ] || exit 1
printf '✓ ledger: %s فایلِ بالای سقف، جمعا %s خط (بودجه %s)\n' \
  "$(echo "$PINS" | sed '/^[[:space:]]*$/d' | wc -l | tr -d ' ')" "$total" "$BUDGET"
