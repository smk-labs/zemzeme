// تست طلاییِ دروازه‌ی کامل بودن. بی‌شبکه، بی‌کلید، در کمتر از یک ثانیه.
//
// این دروازه تنها چیزی است که جلوی «مدل بی‌صدا یک جمله را خورد» را می‌گیرد، و دو
// طرفِ خرابی دارد که هر دو بد است: خیلی سخت‌گیر باشد هر پاس درستی را رد می‌کند و
// فیچر بی‌فایده می‌شود؛ خیلی دست‌ودل‌باز باشد محتوای گم‌شده را قبول می‌کند. پس هر دو
// طرف تست دارد.
//
// اجرا: bash tools/gate_test.sh
#import <Foundation/Foundation.h>
#import "zemzeme.h"

static int gFail;

static void ok(BOOL cond, NSString *what) {
    if (cond) return;
    gFail++;
    printf("  FAIL  %s\n", what.UTF8String);
}

static void pass(NSString *name, NSString *draft, NSString *out) {
    ZCoverage *c = [ZCoverage ofDraft:draft output:out];
    ok(c.passed, [NSString stringWithFormat:@"%@ باید قبول شود — %@", name, c.summary]);
}

static void reject(NSString *name, NSString *draft, NSString *out) {
    ZCoverage *c = [ZCoverage ofDraft:draft output:out];
    ok(!c.passed, [NSString stringWithFormat:@"%@ باید رد شود — %@", name, c.summary]);
}

int main(void) {
    @autoreleasepool {
        // ---------- تحمل صفر روی عدد و لاتین ----------
        reject(@"عدد افتاده",
               @"جلسه ساعت ۱۰ صبح چهارشنبه است و بودجه ۲۵۰ میلیون",
               @"جلسه ساعت ۱۰ صبح چهارشنبه است و بودجه میلیون");
        reject(@"عدد عوض شده",
               @"پورت ۱۷۶۳۶ را باز کن",
               @"پورت ۱۷۶۳۵ را باز کن");
        reject(@"لاتین افتاده",
               @"روی branch اصلی commit کردم و بعد push",
               @"روی branch اصلی commit کردم و بعد");
        pass(@"عدد و لاتین کامل، فقط فیلر رفته",
             @"خب یعنی روی branch اصلی commit کردم ساعت ۱۰ و بعد push کردم دیگه",
             @"روی branch اصلی commit کردم ساعت ۱۰ و بعد push کردم.");

        // ---------- فیلر رفته: باید قبول شود ----------
        pass(@"فیلر و من‌من",
             @"اوم خب می‌خواستم بگم که اِ این سامانه پایاداد خراب بود و محصول وارد نمی‌شد",
             @"می‌خواستم بگم این سامانه پایاداد خراب بود و محصول وارد نمی‌شد.");
        pass(@"خودتصحیحی گوینده",
             @"جلسه سه‌شنبه نه ببخشید چهارشنبه ساعت ۹ است",
             @"جلسه چهارشنبه ساعت ۹ است.");

        // ---------- دو باگی که در آزمایشگاه درست شد ----------
        // بی این دو، هر نیم‌فاصله‌ی درستِ پاس یک «واژه‌ی جاافتاده» شمرده می‌شد و دروازه
        // روی خروجیِ کاملا سالم می‌بست. مهم‌ترین تست همین چهار تاست.
        pass(@"نیم‌فاصله‌ی تازه: میکنه ← می‌کنه",
             @"این کار میکنه و اون یکی هم کار میکنه و همه چیز درست میشه",
             @"این کار می‌کنه و اون یکی هم کار می‌کنه و همه چیز درست می‌شه.");
        pass(@"نیم‌فاصله‌ی برداشته‌شده: می شود ← می‌شود",
             @"این متن پاک می شود و بعد نوشته می شود توی فایلها",
             @"این متن پاک می‌شود و بعد نوشته می‌شود توی فایل‌ها.");
        pass(@"جمعِ ها با نیم‌فاصله",
             @"بچه ها و پروژه ها و فایل ها همه سر جایشان هستند",
             @"بچه‌ها و پروژه‌ها و فایل‌ها همه سر جایشان هستند.");
        pass(@"ارقام فارسی و لاتین یکی شمرده می‌شوند",
             @"ساعت 10 و 30 دقیقه، پورت 8080",
             @"ساعت ۱۰ و ۳۰ دقیقه، پورت ۸۰۸۰.");
        pass(@"عربی و فارسی یکی شمرده می‌شوند",
             @"كتاب را به على دادم",    // ك و ي عربی
             @"کتاب را به علی دادم.");

        // ---------- محتوای واقعیِ گم‌شده ----------
        reject(@"یک جمله‌ی کامل خورده شد",
               @"سامانه خراب بود محصول نمی‌شد وارد کرد و کاربر هم نمی‌توانست سفارش ثبت کند "
               @"و پشتیبانی جواب نمی‌داد و کل روز از دست رفت و تیم فنی هم دسترسی نداشت",
               @"سامانه خراب بود و کل روز از دست رفت.");
        reject(@"اسم خاص افتاد",
               @"شرکت پایاداد قرارداد را با اسنپ بست",
               @"شرکت قرارداد را بست");

        // ---------- ایدمپوتنت: پاس روی خودش ----------
        NSString *polished = @"روی branch اصلی commit کردم ساعت ۱۰ و بعد push کردم. "
                              @"این کار می‌کنه و فایل‌ها سر جایشان هستند.";
        pass(@"متنِ پاس‌خورده در برابر خودش", polished, polished);
        ZCoverage *self0 = [ZCoverage ofDraft:polished output:polished];
        ok(self0.coverage == 100.0, [NSString stringWithFormat:
            @"پوشش متن با خودش باید صد باشد، %.1f شد", self0.coverage]);
        ok(self0.missing.count == 0, @"متن با خودش نباید واژه‌ی جاافتاده داشته باشد");

        // ---------- لبه‌ها ----------
        ZCoverage *empty = [ZCoverage ofDraft:@"" output:@""];
        ok(empty.passed, @"دو متن خالی نباید رد شوند");
        ZCoverage *gone = [ZCoverage ofDraft:@"یک جمله‌ی واقعی با محتوای مشخص و اسم پایاداد" output:@""];
        ok(!gone.passed, @"خروجی خالی باید رد شود");
        ok(gone.coverage == 0.0, @"خروجی خالی پوشش صفر دارد");

        // آستانه: تقریبا همه‌چیز سر جایش، یکی دو واژه‌ی محتوایی رفته. باید قبول شود،
        // وگرنه دروازه روی هر پاس درستی می‌بست.
        pass(@"یک واژه‌ی محتوایی از سی تا رفته",
             @"دیروز رفتم دفتر و با تیم فنی نشستیم و درباره‌ی معماری تازه حرف زدیم و "
             @"قرار شد تا آخر هفته یک نمونه‌ی کوچک بسازیم و بعد تصمیم بگیریم چطور "
             @"باید بقیه‌ی سامانه را هم به همان شکل ببریم و مهاجرت را شروع کنیم دیگه",
             @"دیروز رفتم دفتر و با تیم فنی نشستیم و درباره‌ی معماری تازه حرف زدیم. "
             @"قرار شد تا آخر هفته یک نمونه‌ی کوچک بسازیم و بعد تصمیم بگیریم چطور "
             @"باید بقیه‌ی سامانه را هم به همان شکل ببریم و شروع کنیم.");

        printf(gFail ? "\ngate_test: %d FAIL\n" : "\ngate_test: OK\n", gFail);
    }
    return gFail ? 1 : 0;
}
