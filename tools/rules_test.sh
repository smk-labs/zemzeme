#!/bin/bash
# تستِ طلایی: قاعده‌هایی که یک اسکریپت می‌تواند بشمارد، پس یک اسکریپت می‌شمارد.
#
# چرا این فایل هست: قاعده‌ای که شمردنی است و کسی نمی‌شمارَدش، نقض می‌شود. شاهدش از
# خودِ همین ریپوست و تازه: ۲۲ آگوست ۲۰۲۶، ۷۸ خط تیره‌ی بلند پیدا شد که ۵۳ تایش همان
# روز و در یک سشن وارد شده بود، در فایل‌هایی که همان سشن نوشت، برخلاف قاعده‌ای که
# نوشته بود «هیچ‌وقت». نوشته بود و شمرده نمی‌شد.
#
# هر بند اینجا یک خرابیِ واقعیِ تاریخ‌دار دارد. بند بی خرابی جا ندارد.
# بی کامپایلر و بی مک هم اجرا می‌شود، پس روی ویندوز هم قرمز و سبز می‌شود.
#
# ---------- چرا شمارنده‌ی نویسه‌ها python3 است و نه grep ----------
# دو بارِ اول با grep نوشته شد و **هیچ‌وقت اجرا نشد**، در هر دو جهت:
#
#   • کلاسِ یونیکد: grep بی -P «Invalid range end» می‌دهد و grep -P روی این محیط
#     «supports only unibyte and UTF-8 locales». هر دو خروجیِ خالی می‌دهند و خروجیِ
#     خالی عینا مثل «پاک است» خوانده می‌شد. مکِ هدف هم grep بی‌اسدی دارد که -P ندارد.
#   • نویسه‌ی لفظی در الگو: خودِ همین فایل اولین نقضِ قاعده‌ی خودش می‌شد و گارد از
#     روزِ اول قرمز می‌ماند.
#
# پس نویسه‌ها با کدپوینت شمرده می‌شوند، و «اجرا نشد» نتیجه‌ای صریح است که سبز نیست.
set -uo pipefail
cd "$(dirname "$0")/.."

fail=0
say() { printf '✗ %s\n' "$1" >&2; fail=1; }

# فایل‌های متنیِ ردیابی‌شده. باینری‌ها بیرون‌اند، وگرنه grep روی wav معنا ندارد.
texts() { git ls-files | grep -vE '\.(png|wav|ttf)$'; }
srcs()  { git ls-files 'app/Sources-objc/*.m' 'app/Sources-objc/*.h'; }

if ! command -v python3 >/dev/null 2>&1; then
  say "python3 نیست، پس بندهای ۱ و ۴ اجرا نشدند. «اجرا نشد» سبز نیست."
  chars() { echo ""; }
else
  # شمارِ رخدادِ نویسه با کدپوینت. فهرستِ فایل روی stdin، بازه‌ها در argv (هگز).
  # خروجی یک عدد است، یا خالی اگر خودش خطا خورد.
  chars() { python3 -c '
import sys, io
rs = []
for a in sys.argv[1:]:
    lo, _, hi = a.partition("-")
    rs.append((int(lo, 16), int(hi or lo, 16)))
n = 0
for p in sys.stdin.read().split():
    try: t = io.open(p, encoding="utf-8").read()
    except Exception: continue
    n += sum(1 for c in t if any(a <= ord(c) <= b for a, b in rs))
print(n)
' "$@" 2>/dev/null; }
fi

# شمردنِ رخداد (نه فایل) برای الگوهای اسکی. سنجاق روی رخداد است، چون یک نقضِ دومِ
# داخلِ فایلِ فهرست‌شده نباید سبز رد شود.
count() { local pat=$1; shift; local n=0 f
  for f in "$@"; do n=$((n + $(grep -o -- "$pat" "$f" 2>/dev/null | wc -l))); done
  echo "$n"; }

# ---------- بند ۱: خط تیره‌ی بلند و نیم‌خط تیره ----------
# ۲۲ آگوست ۲۰۲۶: ۷۸ رخداد، ۵۳ تایش همان روز وارد شده بود. همه به نقطه و ویرگول و
# دونقطه تبدیل شدند. سقف صفر است و این بند بلوک است نه هشدار: نویسه یا هست یا نیست.
# 2014 خط تیره‌ی بلند، 2013 نیم‌خط تیره.
n=$(texts | chars 2014 2013)
if [ -z "$n" ]; then say "بند ۱ اجرا نشد: شمارنده جواب نداد."
else [ "$n" -eq 0 ] || say "خط تیره: $n رخداد. نقطه یا ویرگول یا دونقطه یا پرانتز بگذار."
fi

# ---------- بند ۲: مفسرِ بی‌نسخه، در دستور نه در نثر ----------
# ۲۲ آگوست ۲۰۲۶: دستورِ اندازه‌گیریِ M7 در سندِ خونه‌تکونی این ابزار را بی ۳ صدا
# می‌زد. روی مکِ هدف آن نامِ بی‌شماره وجود ندارد، پس دستوری که سندِ اندازه‌گیری به آن
# تکیه داشت روی همان دستگاه هیچ‌وقت اجرا نمی‌شد و کسی نفهمید.
#
# دامنه‌اش عمدا **دستور** است نه هر جای متن: نثری که همین خرابی را شرح می‌دهد مجبور
# است نامش را ببرد، و گاردی که آن را قرمز کند تا ابد قرمز می‌ماند. پس اسکریپت‌ها
# کامل، و در markdown فقط خطی که خودش یک دستور است.
# و توکن سرِ اجرا ساخته می‌شود، نه لفظی در این فایل: دو خطِ اولِ همین بند خودشان
# اولین نقضِ قاعده‌ی خودشان بودند و گارد دو مثبتِ کاذبِ ماندگار می‌داد.
TOK="p""ython"
n=0
for f in $(git ls-files '*.sh'); do
  n=$((n + $(grep -c "\b${TOK}\b" "$f" 2>/dev/null)))
done
for f in $(git ls-files '*.md'); do
  n=$((n + $(grep -cE "^[[:space:]]*${TOK}[[:space:]]" "$f" 2>/dev/null)))
done
[ "$n" -eq 0 ] || say "نامِ بی‌شماره‌ی مفسر در $n دستور. روی مکِ هدف فقط نسخه‌ی ۳ هست."

# ---------- بند ۳: NSLog جای ZLog ----------
# سرآیند صریح است: ZLog سرِ هر روزِ تازه یک خطِ نشانه با ZLogDayPrefix می‌گذارد و
# جاروی روزانه از روی همان می‌برد. «بی این نشانه، لاگ برای همیشه بزرگ می‌شد.»
# NSLog آن نشانه را نمی‌گذارد، پس هر خطش از دستِ جارو در امان است. امروز صفر است.
n=$(count 'NSLog(' $(srcs))
[ "$n" -eq 0 ] || say "NSLog: $n جا. ZLog بگذار، وگرنه آن خط از جاروی روزانه جا می‌ماند."

# ---------- بند ۴: ایموجی در سورس ----------
# نشانِ این اپ برداری است (mark.m) و آیکون‌ها SF Symbol اند. ایموجی روی مانیتورهای
# مختلف و لای متنِ راست‌به‌چپ جابه‌جا رندر می‌شود.
#
# و دامنه‌اش از خودِ ریپو درآمد، نه از یک فهرست. نسخه‌ی اول بازه‌ی 2600 تا 27BF را هم
# می‌گرفت و ۸ مورد داد که **هر هشت درست بودند**: پنج علامتِ هشدار و سه ضربدر، هر
# کدام با FE0E، یعنی «متنی رندر شو نه ایموجی». ریپو از قبل عمدا این کار را می‌کند،
# پس سنجاق‌کردنِ آن هشت تا دروغِ گواهی‌شده می‌شد و تشخیص باریک شد: ایموجیِ محض
# (1F000 تا 1FAFF)، و FE0F که یک نشانه را به ایموجی وادار می‌کند.
n=$(srcs | chars 1F000-1FAFF FE0F)
if [ -z "$n" ]; then say "بند ۴ اجرا نشد: شمارنده جواب نداد."
else [ "$n" -eq 0 ] || say "ایموجی: $n جا در سورس. نشانِ برداری یا SF Symbol بگذار."
fi

# ---------- بند ۵: زبانِ پیش‌فرض، رشته‌ی تکراری ----------
# واحد U12 در سندِ خونه‌تکونی: رشته‌ی زبانِ پیش‌فرض در چند جا تکرار شده و باید یک ثابت
# شود. سنجاق امروز ۱۲ است و فقط پایین می‌آید، پس آن واحد خطِ پایان دارد. سقف صفر
# نیست چون تعمیرش یک واحدِ واقعی است، نه یک جای‌گذاری.
FA_PIN=12
n=$(count '@"fa-IR"' $(srcs))
[ "$n" -le "$FA_PIN" ] || say "زبانِ پیش‌فرض: از $FA_PIN به $n رسید. این رشته فقط کم می‌شود (U12)."

# ---------- بند ۶: لایه‌ی گفته‌شده دروغ نگوید ----------
# CLAUDE.md نمی‌تواند شکست بخورد، پس تنها گاردش این است: هست، از سقفِ بایتش رد نشده،
# و دستوری که به‌عنوان گیت نام می‌برد همان دستوری است که واقعا می‌دود. تطابق، نه
# وجود: وگرنه یک تغییرِ نام سبز رد می‌شود.
CLAUDE_CAP=6000    # بایت، نه خط: یک فایل می‌تواند خطش کم و وزنش زیاد شود.
if [ ! -f CLAUDE.md ]; then
  say "CLAUDE.md نیست. لایه‌ی گفته‌شده جایی است که مدل پیش از نوشتن می‌خواند."
else
  b=$(wc -c < CLAUDE.md | tr -d ' ')
  [ "$b" -le "$CLAUDE_CAP" ] || say "CLAUDE.md $b بایت شد، سقف $CLAUDE_CAP. قاعده‌ی تازه یکی را بیرون می‌کند."
  grep -q 'bash tools/release.sh' CLAUDE.md ||
    say "CLAUDE.md دستورِ گیت را نام نمی‌برد. بی آن، خواننده نمی‌داند چه چیزی باید سبز شود."
  grep -q 'tools/\*_test.sh' tools/release.sh ||
    say "release.sh دیگر گلاب نمی‌کند، ولی CLAUDE.md می‌گوید می‌کند. یکی‌شان غلط است."
fi

# ---------- بند ۷: شمارِ کلِ بندها، با بندِ جابه‌جایی ----------
# آخرین بند و بعد از همه: وگرنه سقف خودش دلیلِ ماندنِ یک قاعده در نثر می‌شود.
# قاعده‌ای که وارد می‌شود یکی را بیرون می‌کند. عدد فقط پایین می‌آید.
RULES=7
n=$(grep -c '^# ---------- بند ' "$0")
[ "$n" -eq "$RULES" ] || say "شمارِ بندها $n شد، سنجاق $RULES. بندِ تازه یعنی یک بندِ کهنه بازنشسته شود."

[ "$fail" = 0 ] || { printf '\nقاعده‌ی شمردنی که شمرده نشود، نقض می‌شود.\n' >&2; exit 1; }
printf '✓ rules: %s بند سبز (خط تیره ۰، دستورِ نسخه‌دار، ZLog، بی‌ایموجی، fa-IR ≤%s، CLAUDE.md ≤%s بایت)\n' \
  "$RULES" "$FA_PIN" "$CLAUDE_CAP"
