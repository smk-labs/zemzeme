// تست طلاییِ دروازه‌ی بهبود پرامپت. بی‌شبکه، بی‌کلید، در کمتر از یک ثانیه.
//
// چرا لازم است: خودِ بهبود پرامپت را نمی‌شود ارزان تست کرد (هر اجرا یک تماس شبکه‌ای و
// یک واحد از سهمِ روزانه‌ی ۲۰ درخواستی است، و همان سهم یک بار وسط ست طلایی تمام شد و
// پنج کیس اجرا نشدند). ولی همه‌ی تصمیم‌های «قبول یا رد» در همین چند تابع‌اند، و آن‌ها
// را می‌شود بی هیچ تماسی سنجید.
//
// و دو طرفِ خرابی دارد که هر دو بد است: خیلی سخت‌گیر باشد هر پرامپت درستی را رد می‌کند
// و فیچر بی‌فایده می‌شود؛ خیلی دست‌ودل‌باز باشد خواسته‌ی گم‌شده را قبول می‌کند و کاربر
// یک پرامپتِ ناقص به ایجنت می‌دهد. پس هر دو طرف تست دارد.
//
// اجرا: bash tools/enhance_gate_test.sh
#import <Foundation/Foundation.h>
#import "zemzeme.h"

static int gFail;

static void ok(BOOL cond, NSString *what) {
    if (cond) return;
    gFail++;
    printf("  FAIL  %s\n", what.UTF8String);
}

static void pass(NSString *name, NSString *draft, NSString *out) {
    ZEnhGate *g = [ZEnhGate ofDraft:draft output:out];
    ok(g.passed, [NSString stringWithFormat:@"%@ باید قبول شود — %@", name, g.summary]);
}

static void reject(NSString *name, NSString *draft, NSString *out) {
    ZEnhGate *g = [ZEnhGate ofDraft:draft output:out];
    ok(!g.passed, [NSString stringWithFormat:@"%@ باید رد شود — %@", name, g.summary]);
}

// یک پرامپتِ ساختاردارِ نمونه، برای تستِ سقف طول. کوتاه‌تر از سقف در همه‌ی کیس‌ها.
static NSString *body(void) {
    return @"# خواسته\nیک اسکریپت که لاگ را بخواند.\n\n"
            "## محدودیت‌ها\n- بدون پکیج بیرونی\n- خط به خط\n\n"
            "## معیار پذیرش\nخروجی درست باشد.\n";
}

int main(void) {
    @autoreleasepool {
        // ---------- تحمل صفر: عدد ----------
        reject(@"عدد افتاده",
               @"سقف را بگذار ۴۸ ساعت و پورت ۶۳۷۹",
               @"# خواسته\nسقف را بگذار ۴۸ ساعت.");
        reject(@"عدد عوض شده",
               @"کش را ۱۰ دقیقه بگذار",
               @"# خواسته\nکش را ۱۵ دقیقه بگذار.");
        pass(@"عددها مانده‌اند، فقط فیلر رفته",
             @"خب اِ کش را ۱۰ دقیقه بگذار و پورت ۶۳۷۹ باشه دیگه",
             @"# خواسته\nکش را ۱۰ دقیقه بگذار.\n\n## محدودیت‌ها\n- پورت ۶۳۷۹");
        pass(@"ارقام فارسی به لاتین، همان عدد",
             @"کش را ۱۰ دقیقه بگذار و پورت ۶۳۷۹",
             @"# خواسته\nکش را 10 دقیقه بگذار.\n\n## محدودیت‌ها\n- پورت 6379");

        // ---------- عددِ مقیاس‌دار: باگ اندازه‌گیری‌شده ----------
        // روی یک دیکته‌ی واقعیِ ۷۸۰ واژه‌ای، گوینده گفت «کد پشت ۱۰ هزار تا سفارش» و
        // پرامپت درست نوشت «تا 10000 سفارش». توکنِ `10` رفت ولی عدد نرفت. دروازه بست و
        // دو تماس و ۴۱ ثانیه سوخت تا همان جوابِ درست دوباره رد شود.
        pass(@"«۱۰ هزار» به 10000",
             @"کدی که پشت ۱۰ هزار تا سفارش در روز جواب بدهد",
             @"# خواسته\nکدی که تا 10000 سفارش در روز را جواب بدهد.");
        pass(@"«۲ میلیون» به 2000000",
             @"دیتابیس باید ۲ میلیون ردیف را بگیرد",
             @"# خواسته\nدیتابیس باید 2000000 ردیف را بگیرد.");
        // ...ولی تحمل تنگ است: بی واژه‌ی مقیاس، هیچ عددی داخل عددِ درازتر بخشیده نمی‌شود
        reject(@"بی واژه‌ی مقیاس، عددِ درازتر بخشش نیست",
               @"صفحه‌ی ۱۲ را باز کن",
               @"# خواسته\nصفحه‌ی ۱۲۳ را باز کن.");

        // ---------- تحمل صفر: توکن لاتین ----------
        reject(@"نام ابزار افتاده",
               @"با python3 بنویس و از pip استفاده نکن",
               @"# خواسته\nبا python3 بنویس.");
        pass(@"همه‌ی لاتین‌ها مانده‌اند",
             @"خب با python3 بنویس و اِ از pip استفاده نکن دیگه",
             @"# خواسته\nبا python3 بنویس.\n\n## محدودیت‌ها\n- بدون pip");
        // مارک‌داون واژه‌ی سر تیتر را بزرگ می‌کند. با تطبیقِ حساس به حرف، هر پرامپت
        // انگلیسیِ درستی رد می‌شد؛ همان چیزی که در اجرای اول ست طلایی بیرون زد.
        pass(@"حرف بزرگ سر تیتر، همان واژه است",
             @"um so reload the nginx config after every deploy okay",
             @"# Task\nReload the Nginx config after every Deploy.");
        // ...ولی فیلرِ زیاد بهانه نیست: شناسه‌ی واقعی هر جا بیفتد، رد است.
        reject(@"شناسه افتاده، هرچند دور و برش فیلر است",
               @"um so you know just call the ZSeamFind helper okay",
               @"# Task\nCall the helper.");

        // ---------- تحمل صفر: مسیر فایل ----------
        // چرا جدا از توکن لاتین: `ZCoverage` مسیر را به تکه‌هایش می‌شکند، پس مسیری که
        // تکه‌هایش پراکنده در متن باشند از دستش رد می‌شود. ایجنت آن‌وقت جای اشتباهی را
        // باز می‌کند و این بدترین شکلِ خرابی است: پرامپت درست به نظر می‌رسد.
        reject(@"مسیر افتاده",
               @"لاگ‌ها در var/log/nginx/access.log هستند و خروجی در tmp/errors.csv",
               @"# خواسته\nلاگ‌ها در var/log/nginx/access.log را بخوان.");
        reject(@"مسیر تکه‌تکه شده",
               @"فایل app/Sources-objc/enhance.m را بخوان",
               @"# خواسته\nفایل enhance.m را در پوشه‌ی app بخوان.");
        pass(@"هر دو مسیر مانده‌اند، حتی داخل بک‌تیک",
             @"لاگ‌ها در var/log/nginx/access.log هستند و خروجی در tmp/errors.csv",
             @"# خواسته\nاز `var/log/nginx/access.log` بخوان.\n\n"
              "## خروجی\n`tmp/errors.csv`");
        pass(@"تاریخ فارسی مسیر نیست",
             @"جلسه ۱۴۰۴/۰۵/۰۱ بود",
             @"# خواسته\nجلسه‌ی ۱۴۰۴/۰۵/۰۱ را خلاصه کن.");

        // ---------- سقف طول ----------
        // پرحرفی هم یک شکلِ خرابی است: پرامپتی که حرفِ اضافه دارد، ایجنت را گمراه می‌کند.
        NSMutableString *windy = [NSMutableString string];
        for (int i = 0; i < 60; i++) [windy appendString:@"و همچنین باید در نظر گرفته شود که "];
        reject(@"پرحرف", @"یک اسکریپت بنویس که لاگ را بخواند", windy);
        // و کفِ مطلق: ورودیِ کوتاه با ضریبِ تنها همیشه رد می‌شد، چون ساختار هزینه‌ی
        // ثابت دارد. شانزده واژه ورودی و ۲٫۵ برابرش چهل؛ هیچ پرامپت درستی در چهل واژه
        // جا نمی‌شود.
        pass(@"ورودیِ کوتاه، پرامپتِ ساختاردار",
             @"یه تست برای تابع ZSeamFind بنویس که مطمئن شه دو تا متن هم‌پوشان درست جوش می‌خورن",
             ([@"# خواسته\nیک تست برای ZSeamFind بنویس.\n\n" stringByAppendingString:body()]));

        // ---------- سشن انگلیسی ----------
        pass(@"انگلیسی، همه‌ی عدد و مسیر مانده",
             @"okay so um refactor src/middleware/auth.ts and cache for 10 minutes on port 6379",
             @"# Task\nRefactor `src/middleware/auth.ts`.\n\n"
              "## Constraints\n- Cache for 10 minutes\n- Redis on port 6379\n");
        reject(@"انگلیسی، مسیر افتاده",
               @"refactor src/middleware/auth.ts and cache for 10 minutes",
               @"# Task\nRefactor the auth middleware and cache for 10 minutes.");

        // ---------- کیس منفی: بلندبلند فکر کردن ----------
        // خروجی درست اینجا یک پرامپت الکی نیست، پرسیدنِ همان ابهام است. دروازه این را
        // نمی‌سنجد (کارِ پرامپت است)، ولی باید جلویش را هم **نگیرد**: متنی که هیچ عدد و
        // مسیری ندارد نباید به بهانه‌ی «چیزی گم شد» رد شود.
        pass(@"بی عدد و بی مسیر، فقط ابهام",
             @"نمی‌دونم یعنی این قضیه‌ی کش کردن هی به ذهنم می‌رسه ولی نمی‌دونم شاید مشکل جای دیگه‌ای باشه",
             @"# خواسته\nروشن نیست.\n\n## مفروضات و سوال‌های باز\n"
              "- کدام بخش کند است؟\n- کهنه شدن داده چقدر قابل تحمل است؟\n");

        // ---------- خالی و مرزی ----------
        pass(@"ورودی خالی", @"", @"# خواسته\nچیزی گفته نشده.");

        printf(gFail ? "  %d تست شکست\n" : "  همه‌ی تست‌های دروازه‌ی بهبود پرامپت قبول\n", gFail);
        return gFail ? 1 : 0;
    }
}
