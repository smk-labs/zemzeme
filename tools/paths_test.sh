#!/bin/bash
# تستِ طلایی: هر مسیری که در متن‌ها اسمش آمده، واقعا وجود دارد.
#
# چرا این فایل هست: جابه‌جا کردن یا حذفِ یک فایل، تنها کاری است که خرابی‌اش از دیدِ
# همه‌ی گاردهای موجود پنهان می‌ماند، چون هیچ گاردی مسیری را از داخلِ یک کامنت یا یک
# ریدمی نمی‌خواند. دو تا از همین‌ها روی همین ریپو پیدا شد (۲۲ آگوست ۲۰۲۶):
#
#   • app/build.sh خواننده را به پورتِ سوئیفت می‌فرستاد، درختی که دیگر نیست.
#   • tools/release.sh تستِ hole را صدا می‌زد که حذف شده بود، و ریلیز را بریده بود.
#
# پس مسیرهای داخل متن هم گارد دارند. بی کامپایلر و بی مک هم اجرا می‌شود.
set -uo pipefail
cd "$(dirname "$0")/.."

# ---------- بندِ رهایی: اشاره‌ی عمدی به گذشته ----------
# یک یادداشتِ تاریخی حق دارد نامِ چیزی را ببرد که حذف شده («فلان درخت برداشته شد»).
# ولی این حق باید در خودِ متن دیده شود، نه در یک لیستِ دور. پس همان خط باید نشانِ
# [حذف‌شده] یا [deleted] داشته باشد. صریح و گرپ‌شدنی، و تصادفی روشن نمی‌شود.
MARKER='\[(حذف‌شده|deleted)\]'

# ---------- بیرون از گارد ----------
# قاعده‌ی اول کلاسی است، نه فهرستی: مسیری که .gitignore کنارش گذاشته، **قرار نیست**
# روی یک چک‌اوتِ تازه باشد، پس نبودنش خرابی نیست. سه‌تایشان روی همین ریپو مصداق
# دارند و هر سه هم درست‌اند: app/.build/ (بیلدِ محلی)، مسیرهای dmg که با متغیرِ شل
# ساخته می‌شوند، و docs/img/history.png که عمدا وارد گیت نمی‌شود چون متنِ واقعیِ
# دیکته‌ی کاربر است. فهرستِ دستی اینجا سه اسم می‌شد و چهارمی را بی‌صدا جا می‌انداخت.
#
# و یک استثنای واقعی، با دلیل و تاریخ:
# app/win/ ــ ۲۲ آگوست ۲۰۲۶: مسیرِ **آینده** در یک سندِ نقشه (WINDOWS-PORT.md)، نه
#   ادعای وجود. سند می‌گوید «کدِ تازه اینجا می‌نشیند»، پس نبودنش درست است. اگر پورت
#   ویندوز نوشته شد، این خط باید برداشته شود، نه اینکه بماند و بی‌معنا شود.
skip() {
  case "$1" in
    app/win|app/win/*) return 0 ;;
  esac
  git check-ignore -q "$1" 2>/dev/null && return 0
  return 1
}

tmp="${TMPDIR:-/tmp}/zpaths.$$"
: > "$tmp"
trap 'rm -f "$tmp"' EXIT

# .gitignore فایلِ الگو است نه اشاره به مسیرِ موجود، پس در لیستِ زیر نیست.
for f in $(git ls-files '*.md' '*.m' '*.h' '*.sh' '*.json' '*.plist'); do
  # خط‌به‌خط، چون بندِ رهایی خصوصیتِ همان خط است نه همه‌ی فایل.
  while IFS=: read -r ln text; do
    [ -n "${text:-}" ] || continue
    printf '%s' "$text" | grep -qE "$MARKER" && continue
    # مسیرها را با کاراکترِ مرزیِ قبلشان می‌گیریم تا وسطِ یک مسیرِ بزرگ‌تر گیر نکنند:
    # «/Applications/Zemzeme.app/Contents/MacOS/» نباید به «app/Contents/MacOS/» بشکند.
    for p in $(printf '%s' "$text" |
               grep -oE '(^|[[:space:]`"(])(app|tools|docs)/[A-Za-z0-9_./-]+' |
               sed -E 's/^[[:space:]`"(]+//' | sort -u); do
      p="${p%%[.,;:)]}"                  # نقطه یا ویرگولِ آخرِ جمله
      skip "$p" && continue
      [ -e "$p" ] && continue
      # اشاره‌ی بی‌پسوند به یک جفتِ فایل («tools/queue_test» یعنی .m و .sh) درست است.
      compgen -G "$p.*" >/dev/null && continue
      printf '✗ %s:%s مسیرِ ناموجود «%s»\n' "$f" "$ln" "$p" >&2
      echo x >> "$tmp"
    done
  done < <(grep -nE '(app|tools|docs)/' "$f" 2>/dev/null)
done

if [ -s "$tmp" ]; then
  printf '\n%s مسیرِ ناموجود در متن‌ها. یا مسیر را درست کن، یا متن را.\n' "$(wc -l < "$tmp")" >&2
  printf 'اشاره‌ی عمدی به چیزِ حذف‌شده؟ همان خط را با [حذف‌شده] نشان بگذار.\n' >&2
  exit 1
fi
echo "✓ paths: هر مسیرِ نام‌برده‌شده در متن‌ها وجود دارد"
